import assert from 'node:assert/strict';
import {placeName,overlaps} from '../dist/label-layout.js';
const input={anchor:{x:300,y:260},size:{w:150,h:38},pinWidth:24,viewport:{w:800,h:600},obstacles:[]};
const first=placeName(input);assert.equal(first.side,'right');
assert.equal(first.x+18,input.anchor.x);assert.equal(first.y+first.h,input.anchor.y-9);
const left=placeName({...input,obstacles:[{x:340,y:200,w:200,h:60}]});assert.equal(left.side,'left');assert.equal(left.x+left.w-18,input.anchor.x);
const pan=placeName({...input,anchor:{x:320,y:260},previous:left.side});assert.equal(pan.side,'left');assert.equal(pan.x,left.x+20);
assert.equal(placeName({...input,obstacles:[{x:0,y:0,w:800,h:600}]}),null);
const namesOnly=placeName({...input,pinWidth:0});assert.equal(namesOnly.x+namesOnly.w/2,300);
assert.ok(!overlaps(namesOnly,{x:0,y:0,w:800,h:150}));
console.log('Roof anchor, adjacent name collision, stable side and name-only layout verified.');
